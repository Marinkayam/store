--
-- "תיצור לי באדמין אפשרות שאשלח לינק לים או לחברות שלה לנסות את
-- המוצר": ילדה חדשה שנכנסת דרך קישור מהחמ"ל צריכה להיות מסומנת
-- כפיילוט — שתופיע בחמ"ל, ושאישור ההורה יחול עליה — בלי הצעד הנפרד
-- של קישור פיילוט. הטוקן נוצר יחד עם קישור הכניסה וניצמד לחשבון
-- ברגע הכניסה, באותו מנגנון בדיוק כמו במסלול הסמס.

