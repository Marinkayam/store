/**
 * שם האפשרות כפי שמותר להציג לקונה: רק "צבע" או "מידה".
 *
 * לעולם לא מציגים את option_label כמו שהוא. מוצרים ישנים עשויים לשאת ערך
 * חופשי משלב קודם (כמו "בחרי", ברירת המחדל הישנה) — הצגה ישירה שלו יוצרת
 * משפט חסר פשר כמו "בחירת בחרי". "מידה" בלבד מזוהה כמידה; כל דבר אחר, כולל
 * ערך ישן או ריק, מוצג כ"צבע".
 */
export function safeOptionLabel(label: string | null | undefined): string {
  return label === "מידה" ? "מידה" : "צבע";
}
