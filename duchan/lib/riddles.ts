export const STAR_RANKS = [
  { at: 0, name: "מתחילים" },
  { at: 5, name: "ניצוץ של חשבון" },
  { at: 15, name: "מחשבון כיס" },
  { at: 30, name: "קופה רושמת" },
  { at: 60, name: "מוח של שוק" },
  { at: 100, name: "אגדת השוק" },
] as const;

export function rankOf(stars: number) {
  let i = 0;
  STAR_RANKS.forEach((r, j) => {
    if (stars >= r.at) i = j;
  });
  const next = STAR_RANKS[i + 1] ?? null;
  return { index: i, name: STAR_RANKS[i].name, next: next ? { name: next.name, missing: next.at - stars } : null };
}
