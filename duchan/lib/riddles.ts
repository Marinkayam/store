/** כמה גרסאות לכל תבנית */
const VARIANTS = 5;

function finish(id: string, topic: Topic, level: 1 | 2 | 3, m: Make): Riddle | null {
  const opts = [m.answer, ...m.wrong];
  if (new Set(opts).size !== opts.length) return null; // מספרים שיצאו זהים — מדלגים על הגרסה
  return { id, topic, level, q: m.q, answer: m.answer, why: m.why, options: order(id, opts) };
}

/** כל החידות, בסדר קבוע: קל → מאתגר, ונושאים מתחלפים כדי שלא יהיו חמש
 *  חידות חשבון ברצף. */
export function allRiddles(sample: Sample = FALLBACK): Riddle[] {
  const list: Riddle[] = [];
  const seenQ = new Set<string>();
  const push = (r: Riddle | null) => {
    if (r && !seenQ.has(r.q)) {
      seenQ.add(r.q);
      list.push(r);
    }
  };
  for (const f of FIXED) {
    push(finish(`c-${f.id}`, f.topic, f.level, f));
  }
  for (const t of TEMPLATES) {
    for (let v = 0; v < VARIANTS; v++) {
      push(finish(`t-${t.key}-${v}`, t.topic, t.level, t.make(v, sample)));
    }
  }
  // סדר: קודם לפי רמה, ובתוך רמה מערבבים נושאים (סבב) וגרסאות
  const byLevel = [1, 2, 3].map((lv) => list.filter((r) => r.level === lv));
  const out: Riddle[] = [];
  for (const group of byLevel) {
    const topics = new Map<string, Riddle[]>();
    for (const r of group) topics.set(r.topic, [...(topics.get(r.topic) ?? []), r]);
    // תבניות: גרסה 0 של כולן לפני גרסה 1 — כך אין את אותה שאלה פעמיים ברצף
    for (const arr of topics.values()) arr.sort((a, b) => variantOf(a.id) - variantOf(b.id));
    const queues = [...topics.values()];
    while (queues.some((q) => q.length)) for (const q of queues) if (q.length) out.push(q.shift()!);
  }
  return out;
}

function variantOf(id: string): number {
  const m = id.match(/-(\d+)$/);
  return id.startsWith("t-") && m ? Number(m[1]) : 0;
}

/** החידה הבאה שעוד לא נפתרה, או null כשנפתרו כולן */
export function nextRiddle(solved: string[], sample?: Sample): Riddle | null {
  const done = new Set(solved);
  return allRiddles(sample).find((r) => !done.has(r.id)) ?? null;
}

