import type { BadgeKey } from "./kupa";

/**
 * חידת סוחר/ת לכל אות בקופת הדוכן — חשבון וצרכנות, מתוך מה שקורה בדוכן.
 *
 * מרינה: "שיהיה מלמד משהו על צרכנות, על חשבון". כל חידה היא שאלה אחת
 * עם שלוש תשובות, ואחרי התשובה מסבירים למה — גם כשטועים. אין עונש ואין
 * שעון: אפשר לנסות שוב עד שמצליחים.
 *
 * כשיש בדוכן מוצר עם מחיר, השאלה משתמשת בו ("‘צמיד קשת’ עולה ₪12…"),
 * כי חשבון על המוצר שלי מעניין יותר מחשבון על תפוחים.
 */

export type Topic = "חשבון" | "צרכנות" | "עסק";

export interface Lesson {
  topic: Topic;
  q: string;
  options: string[];
  answer: string;
  why: string;
}

export interface Sample {
  name: string;
  price: number;
}

const FALLBACK: Sample = { name: "מחזיק מפתחות", price: 12 };
const sh = (n: number) => `₪${Number.isInteger(n) ? n : n.toFixed(2)}`;

/** סדר קבוע לכל חידה (לא אקראי בכל רינדור), כדי שהתשובה לא תקפוץ */
function order(key: string, opts: string[]): string[] {
  let h = 0;
  for (const c of key) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  const a = [...opts];
  for (let i = a.length - 1; i > 0; i--) {
    h = (h * 1103515245 + 12345) >>> 0;
    const j = h % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** מוצר "נוח לחשבון": מחיר שלם בין 2 ל-200 */
export function pickSample(products: { name: string; price: number | string }[]): Sample {
  const ok = products
    .map((p) => ({ name: p.name, price: Number(p.price) }))
    .find((p) => Number.isInteger(p.price) && p.price >= 2 && p.price <= 200 && p.name.length <= 24);
  return ok ?? FALLBACK;
}

export function lessonFor(key: BadgeKey, sample: Sample = FALLBACK): Lesson {
  const P = sample.price;
  const N = `‘${sample.name}’`;
  const L = (topic: Topic, q: string, answer: string, wrong: string[], why: string): Lesson => ({
    topic, q, answer, why, options: order(key, [answer, ...wrong]),
  });

  switch (key) {
    case "open":
      return L("חשבון", "בדוכן יש 3 צמידים, כל אחד ב-₪8. אם כולם יימכרו, כמה כסף ייכנס?",
        "₪24", ["₪11", "₪38"],
        "3 × ₪8 = ₪24. כפל הוא הדרך המהירה לחבר את אותו מחיר כמה פעמים.");
    case "first_product":
      return L("חשבון", `${N} עולה ${sh(P)}. שלושה חברים קונים אחד כל אחד. כמה כסף ייכנס?`,
        sh(P * 3), [sh(P + 3), sh(P * 4)],
        `3 × ${sh(P)} = ${sh(P * 3)}. ככה בודקים מראש כמה אפשר להרוויח מכמה מכירות.`);
    case "photo":
      return L("צרכנות", "שני דוכנים מוכרים אותו סקוויש באותו מחיר. מה יגרום לקנות דווקא מאחד מהם?",
        "תמונה ברורה שרואים בה את המוצר", ["שם ארוך יותר למוצר", "הרבה סימני קריאה בתיאור"],
        "קונים סומכים על מה שהם רואים. תמונה טובה = פחות הפתעות ויותר קונים שחוזרים.");
    case "pay_ready":
      return L("חשבון", "הזמנה עולה ₪35. משלמים במזומן עם שטר של ₪50. כמה עודף מחזירים?",
        "₪15", ["₪25", "₪5"],
        "₪50 − ₪35 = ₪15. כדאי להכין מטבעות לעודף לפני שנפגשים למסירה.");
    case "about":
      return L("צרכנות", "מה הכי עוזר לקונה חדש לסמוך על הדוכן?",
        "משפט אמיתי על מי מוכר ומה מיוחד", ["לכתוב ‘הכי זול בעולם’", "לא לספר כלום"],
        "אמת בונה אמון. הבטחות מוגזמות גורמות לקונים לחשוד, גם כשהמוצר טוב.");
    case "five_products": {
      const base = P % 10 === 0 && P >= 10 ? P : 20;
      const off = base / 10;
      return L("חשבון", `מוצר עולה ${sh(base)}. עושים מבצע של 10% הנחה. כמה הוא יעלה אחרי ההנחה?`,
        sh(base - off), [sh(base / 2), sh(base + off)],
        `10% זה עשירית. עשירית מ-${sh(base)} זה ${sh(off)}, ו-${sh(base)} − ${sh(off)} = ${sh(base - off)}.`);
    }
    case "views10":
      return L("חשבון", "מתוך כל 10 אנשים שנכנסו לדוכן, אחד קנה. אם ייכנסו 50 אנשים, כמה יקנו בערך?",
        "5", ["1", "10"],
        "אחד מכל עשרה זה עשירית. עשירית מ-50 זה 5. ככה עסקים מחשבים כמה כדאי לשתף.");
    case "first_order":
      return L("עסק", "הגיעה הזמנה, אבל עוד לא שילמו. מתי זו מכירה אמיתית?",
        "כשהכסף הגיע", ["כשההזמנה הגיעה", "כשמישהו כתב שהוא אוהב את המוצר"],
        "הזמנה היא הבטחה. מכירה היא כשהכסף אצלך. לכן מסמנים ‘שולם’ רק כשהכסף באמת הגיע.");
    case "first_sale": {
      const cost = Math.max(1, Math.round(P * 0.4));
      return L("חשבון", `הוצאת ${sh(cost)} על החומרים של ${N} ומכרת אותו ב-${sh(P)}. כמה הרווחת?`,
        sh(P - cost), [sh(P), sh(P + cost)],
        `רווח = מחיר המכירה פחות מה שהוצאת: ${sh(P)} − ${sh(cost)} = ${sh(P - cost)}. מה שלא הרווחת הלך לחומרים.`);
    }
    case "views50":
      return L("צרכנות", "מה זול יותר לכל יחידה: 2 ב-₪15, או אחד ב-₪8?",
        "2 ב-₪15", ["אחד ב-₪8", "אותו מחיר בדיוק"],
        "₪15 ÷ 2 = ₪7.50 לאחד, פחות מ-₪8. ‘מחיר ליחידה’ עוזר להשוות, גם בסופר.");
    case "hundred":
      return L("חשבון", "רוצים לחסוך ₪150 לאוזניות. כבר יש ₪100, וכל מכירה מכניסה ₪10. כמה מכירות עוד צריך?",
        "5", ["15", "50"],
        "חסרים ₪50, ו-₪50 ÷ ₪10 = 5 מכירות. מטרה עם מספר קל יותר להשיג.");
    case "ten_sales":
      return L("צרכנות", "הרווחת ₪120 מהדוכן. איזו תוכנית הכי חכמה?",
        "חלק לחיסכון, חלק לחומרים, חלק לפינוק", ["להוציא הכל היום", "לשמור הכל ולא לקנות חומרים"],
        "עסקים מחלקים כסף לתפקידים: חומרים מביאים עוד מוצרים, חיסכון מביא מטרה גדולה, ופינוק הוא הכיף של העבודה.");
  }
}
